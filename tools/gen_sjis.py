#!/usr/bin/env python3
"""Generate the Shift-JIS <-> Unicode table described in spec 01 §2.10 from Python's cp932 codec.

Emits pairs (sjis, codepoint) in ascending SJIS order for every decodable 2-byte code with
lead 0x81-0x9F/0xE0-0xEF and trail 0x40-0x7E/0x80-0xFC.
"""
import sys

out = sys.argv[1]
pairs = []
for h in list(range(0x81, 0xA0)) + list(range(0xE0, 0xF0)):
    for l in list(range(0x40, 0x7F)) + list(range(0x80, 0xFD)):
        try:
            s = bytes([h, l]).decode('cp932')
        except UnicodeDecodeError:
            continue
        if len(s) != 1:
            continue
        pairs.append(((h << 8) | l, ord(s)))

with open(out, 'w') as f:
    f.write('// Generated by tools/gen_sjis.py from the cp932 codec.\n#include <cstdint>\nnamespace core {\n')
    f.write('extern const uint16_t kSjisTable[][2];\nextern const int kSjisTableSize;\n')
    f.write('const uint16_t kSjisTable[][2] = {\n')
    for i in range(0, len(pairs), 8):
        f.write(''.join('{0x%04X,0x%04X},' % p for p in pairs[i:i + 8]) + '\n')
    f.write('};\nconst int kSjisTableSize = %d;\n}\n' % len(pairs))
print(len(pairs), 'pairs', file=sys.stderr)
